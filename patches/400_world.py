"""The rest of the world: every field with story checks that no specific patch
handles is pinned to the moment in patches/world_moments.json (generated by
`ff7tool.py plan-world`; review it) unless patches/world_overrides.json gives
another moment for that field. New-game flags from world_flags.json (generated
by `ff7tool.py quiet-flags`) are applied by 010_new_game.py."""
import json
import os

from ff7.patch import localise_progress
from ff7.script import Script

HERE = os.path.dirname(os.path.abspath(__file__))


def moments():
    plan = json.load(open(os.path.join(HERE, "world_moments.json")))
    out = {f: v["moment"] for f, v in plan.items()}
    overrides = os.path.join(HERE, "world_overrides.json")
    if os.path.exists(overrides):
        out.update({f: m for f, m in json.load(open(overrides)).items() if not f.startswith("_")})
    return out


def apply(ctx):
    for field, moment in sorted(moments().items()):
        sec = Script.parse(ctx.field(field).sections[0])
        localise_progress(sec, const=moment)
        ctx.field(field).sections[0] = sec.build()
