def source_count(level):
    """Sources a quest gives by its area's enemy level: 1 for early Midgar
    (level <= 13), rising evenly to 8 for the highest quest areas (level 50,
    Jenova LIFE)."""
    return min(8, max(1, 1 + (level - 8) * 7 // 42))
