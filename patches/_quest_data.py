"""Quest data for 600_quests.py: who gives which quests, where, and what they say.

Each giver: field, entity name (<= 8 chars), model (donor field, model index),
at (x, y) on that field's walkmesh, dir, who (speaker / log name), where (log
text), quests (offered in order: the next once the previous is done),
all_done (line after the last quest). Optional companion: an extra NPC beside
the giver (model, at, talk text, tinted yellow if chocobo=True).

Each giver also has `level` (the area's enemy level; a quest may override
it): every quest gives source_count(level) of a Source on top of its reward.

Each quest: id (unique; save bytes are allocated in GIVERS order, so append
new quests at the end of a giver's list or add new givers at the end, to keep
existing saves' quest bytes in place; a follow-up appended to an early giver
sets late=True, which allocates it after every other quest), kind "kill" or "deliver",
  kill:    enemies + count + label, or targets=[(label, [enemy ids], count)...]
  deliver: item + count + label, or items=[(label, item id, count)...]
(up to 4 targets/items), title + desc (3 lines <= 46 chars) + labels for the
Quests menu, dialogue pages (M), and reward (gil, items [(id, qty)], materia).
Spots for the new givers were picked with the camera projection: on screen,
35-80 units from a walkmesh edge (out of the walking path), >= 180 from
exits/lines and >= 110 from other NPCs.
"""


def M(speaker, *lines):
    """One message page: speaker line + quoted lines (keep each <= 38 chars)."""
    body = "\n ".join(lines)
    text = "%s\n\u201c%s\u201d" % (speaker, body)
    for line in text.split("\n"):
        assert len(line) <= 38, line
    return text


