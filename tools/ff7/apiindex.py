"""Generate docs/api_index.md: every module, class and function in tools/ and
patches/ with its signature and the first line of its docstring. Regenerate
with `python3 tools/ff7tool.py api-index` (the tests fail if it is stale)."""
import ast
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCES = [("tools/ff7tool.py", None), ("tools/ff7", ".py"), ("patches", ".py")]


def _first_line(node):
    doc = ast.get_docstring(node)
    return doc.strip().split("\n")[0].strip() if doc else ""


def _sig(fn):
    a = fn.args
    parts = [x.arg for x in a.posonlyargs + a.args]
    defaults = [None] * (len(parts) - len(a.defaults)) + list(a.defaults)
    out = [p if d is None else "%s=%s" % (p, ast.unparse(d)) for p, d in zip(parts, defaults)]
    if a.vararg:
        out.append("*" + a.vararg.arg)
    elif a.kwonlyargs:
        out.append("*")
    for k, d in zip(a.kwonlyargs, a.kw_defaults):
        out.append(k.arg if d is None else "%s=%s" % (k.arg, ast.unparse(d)))
    if a.kwarg:
        out.append("**" + a.kwarg.arg)
    return "%s(%s)" % (fn.name, ", ".join(o for o in out if o != "self" and o != "cls"))


def _files():
    for path, ext in SOURCES:
        full = os.path.join(ROOT, path)
        if ext is None:
            yield path
        else:
            for name in sorted(os.listdir(full)):
                if name.endswith(ext):
                    yield path + "/" + name


def generate():
    lines = ["# API index", "",
             "Generated by `python3 tools/ff7tool.py api-index` from the source; do not edit.",
             "`_name` entries are module-private helpers.", ""]
    for rel in _files():
        tree = ast.parse(open(os.path.join(ROOT, rel), encoding="utf-8").read())
        lines.append("## `%s`" % rel)
        doc = _first_line(tree)
        if doc:
            lines.append(doc)
        lines.append("")
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                lines.append("- `%s` %s" % (_sig(node), _first_line(node)))
            elif isinstance(node, ast.ClassDef):
                lines.append("- class `%s` %s" % (node.name, _first_line(node)))
                for m in node.body:
                    if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef)) and \
                            (not m.name.startswith("__") or m.name == "__init__"):
                        lines.append("  - `%s` %s" % (_sig(m), _first_line(m)))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def path():
    return os.path.join(ROOT, "docs", "api_index.md")
